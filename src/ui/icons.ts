const cache = new Map<string, string>();

export function iconUrl(name: string, colors: { o: string; a: string; b: string }): string {
  const k = `${name}|${colors.o}|${colors.a}|${colors.b}`;
  const hit = cache.get(k);
  if (hit) return hit;
  const map = MAPS[name] ?? MAPS.star;
  const c = document.createElement('canvas');
  c.width = 12; c.height = 12;
  const g = c.getContext('2d')!;
  const pal: Record<string, string> = { o: colors.o, a: colors.a, b: colors.b, w: '#FFFFFF', y: '#F7C948', r: '#E8506A', g: '#5CB85C', s: '#BFB3A6' };
  map.forEach((row, y) => [...row].forEach((ch, x) => { const col = pal[ch]; if (col) { g.fillStyle = col; g.fillRect(x, y, 1, 1); } }));
  const url = c.toDataURL();
  cache.set(k, url);
  return url;
}

export const ICONS = Object.keys(MAPS);
